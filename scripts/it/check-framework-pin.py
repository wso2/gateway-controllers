#!/usr/bin/env python3
"""
Check that one file pins the test framework for every integration suite.

Every policy owns an integration suite in policies/<name>/it, a Go module of its own, and all of
them run on one version of the framework, github.com/wso2/api-platform/tests/framework. That
version is written once, in tests/it/go.mod. The workspace file tests/it/it.work, generated by
generate-workspace.py, joins tests/it and every policy's it module, so a suite resolves the framework
to that version without naming it in its own go.mod. Changing the version is one `go get` in tests/it.

The check fails when
  * tests/it/go.mod does not require the framework exactly once at a tagged release, or replaces it;
  * a policy's it/go.mod mentions the framework again (go mod tidy run inside it puts the line
    back, and it would then disagree with tests/it/go.mod).

Exits 1 and prints one line per problem; prints nothing and exits 0 when all is well.
"""

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
FRAMEWORK = "github.com/wso2/api-platform/tests/framework"
RELEASE_RE = re.compile(r"^v\d+\.\d+\.\d+$")
# The framework module itself, not one of its packages (.../cmd/standards in a tool line).
MENTION_RE = re.compile(re.escape(FRAMEWORK) + r"(?=\s|$)")
VERSION_RE = re.compile(re.escape(FRAMEWORK) + r"\s+(v\S+)")


def strip_comment(line):
    return line.split("//", 1)[0]


def framework_lines(go_mod_text):
    """Return (requires, replaces): the versions required and the count of replace lines."""
    requires, replaces = [], 0
    for raw in go_mod_text.splitlines():
        line = strip_comment(raw)
        if not MENTION_RE.search(line):
            continue
        if "=>" in line:
            replaces += 1
            continue
        match = VERSION_RE.search(line)
        if match:
            requires.append(match.group(1))
    return requires, replaces


def check(repo_root):
    problems = []
    root = Path(repo_root)

    framework_mod = root / "tests" / "it" / "go.mod"
    if not framework_mod.is_file():
        problems.append("tests/it/go.mod does not exist")
    else:
        requires, replaces = framework_lines(framework_mod.read_text(encoding="utf-8"))
        if len(requires) != 1:
            problems.append(
                f"tests/it/go.mod must require {FRAMEWORK} exactly once, it does {len(requires)} times"
            )
        elif not RELEASE_RE.match(requires[0]):
            problems.append(
                f"tests/it/go.mod requires {FRAMEWORK} at {requires[0]}, which is not a tagged release (vX.Y.Z)"
            )
        if replaces:
            problems.append(f"tests/it/go.mod replaces {FRAMEWORK}; the suites must run on a published release")

    suites = sorted(path.parent.parent.name for path in root.glob("policies/*/it/go.mod"))
    for name in suites:
        requires, replaces = framework_lines((root / "policies" / name / "it" / "go.mod").read_text(encoding="utf-8"))
        if requires or replaces:
            problems.append(
                f"policies/{name}/it/go.mod mentions {FRAMEWORK}; only tests/it/go.mod pins it "
                "(delete the line, and do not run go mod tidy in the suite without the workspace)"
            )

    return problems


def main():
    problems = check(REPO_ROOT)
    for problem in problems:
        print(f"check-framework-pin: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
